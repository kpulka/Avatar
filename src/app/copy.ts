/**
 * Resolve a slot to its English text, replacing `{key}` markers with `params[key]`.
 * Fail-soft: an unknown slot warns once per call and returns the slot id itself.
 */
export function t(slot: string, params?: Record<string, string | number>): string {
  const template = COPY[slot];
  if (template === undefined) {
    console.warn(`[copy] Unknown copy slot '${slot}'.`);
    return slot;
  }
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match
  );
}
